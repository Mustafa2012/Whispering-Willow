create table if not exists products (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category text not null,
  price numeric not null default 0,
  description text not null default '',
  image text not null default '/placeholder.svg',
  sizes text[] not null default '{}',
  created_at timestamptz not null default now()
);

alter table products add column if not exists is_active boolean not null default true;
alter table products add column if not exists sizes text[] not null default '{}';
alter table products alter column price type numeric using regexp_replace(price::text, '[^0-9.]', '', 'g')::numeric;

create table if not exists orders (
  id bigint generated by default as identity primary key,
  order_number text unique default ('WW-' || upper(substr(md5(random()::text), 1, 8))),
  customer_name text not null,
  email text not null,
  phone text not null,
  address text not null,
  payment_method text not null check (payment_method in ('cod', 'bank_transfer')),
  transaction_reference text,
  proof_url text,
  notes text,
  admin_notes text,
  subtotal numeric not null default 0,
  discount numeric not null default 0,
  discount_code text,
  delivery_charge numeric not null default 250,
  total numeric not null check (total >= 0),
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'processing', 'shipped', 'completed', 'cancelled')),
  created_at timestamptz not null default now()
);

alter table orders add column if not exists user_id uuid references auth.users(id);
alter table orders add column if not exists subtotal numeric not null default 0;
alter table orders add column if not exists discount numeric not null default 0;
alter table orders add column if not exists discount_code text;
alter table orders add column if not exists delivery_charge numeric not null default 250;

create table if not exists order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references orders(id) on delete cascade,
  product_id bigint,
  name text not null,
  price numeric not null,
  quantity integer not null check (quantity > 0),
  total numeric not null check (total >= 0),
  selected_size text
);

alter table order_items add column if not exists selected_size text;

create table if not exists store_settings (
  id boolean primary key default true,
